def policy(name, rules, validations, c, condition=None):
    conditions = [] if name == 'portal-deployer-surface' else [{'name': 'portal-namespace-only', 'expression': 'request.namespace == ' + json.dumps(c['namespace'])}]
    if condition:
        conditions.append({'name': 'restricted-request', 'expression': condition})
    return {'apiVersion': 'admissionregistration.k8s.io/v1', 'kind': 'ValidatingAdmissionPolicy',
            'metadata': {'name': name}, 'spec': {'failurePolicy': 'Fail',
            'matchConstraints': {'resourceRules': rules, 'matchPolicy': 'Equivalent'},
            'matchConditions': conditions,
            'validations': [{'expression': e, 'message': m} for e, m in validations]}}


def binding(name):
    return {'apiVersion': 'admissionregistration.k8s.io/v1', 'kind': 'ValidatingAdmissionPolicyBinding',
            'metadata': {'name': name}, 'spec': {'policyName': name, 'validationActions': ['Deny']}}


def workload_validations(c, prefix):
    p = prefix
    container = p + '.containers[0]'
    i = c['identity']
    values = {'LISTEN_HOST': '0.0.0.0', 'PORTAL_ORIGIN': c['portalOrigin'], 'TENANT_SOURCE': 'disabled',
              'OIDC_ISSUER': i['issuer'], 'OIDC_CLIENT_ID': i['clientId'], 'OIDC_AUDIENCE': i['audience']}
    # Inline CEL literals avoid trusting a tenant-editable ConfigMap/parameter resource.
    env = container + '.env'
    image = c['imageRepository'] + '@' + c['imageDigest'] if c['imageDigest'] else None
    checks = [
        (f'{p}.containers.size() == 1', 'Exactly one approved portal container is required'),
        (f'{container}.name == "portal" && {container}.image == {json.dumps(image)}' if image else 'false', 'No approved image digest' if not image else 'Only the platform-approved image digest is allowed'),
        (f'has({p}.serviceAccountName) && {p}.serviceAccountName == {json.dumps(c["runtimeServiceAccount"])} && has({p}.automountServiceAccountToken) && !{p}.automountServiceAccountToken', 'Platform runtime identity with token automount disabled is required'),
        (f'(!has({p}.initContainers) || {p}.initContainers.size() == 0) && (!has({p}.ephemeralContainers) || {p}.ephemeralContainers.size() == 0)', 'Init and ephemeral containers are forbidden'),
        (f'(!has({p}.volumes) || {p}.volumes.size() == 0) && (!has({p}.imagePullSecrets) || {p}.imagePullSecrets.size() == 0)', 'No mounted volumes or extra secret references are allowed'),
        (f'has({env}) && {env}.size() == 7 && {env}.all(e, {env}.filter(x, x.name == e.name).size() == 1)', 'Exactly the seven unique platform environment entries are required'),
        (f'{env}.all(e, e.name == "OIDC_CLIENT_SECRET" ? (!has(e.value) || e.value == "") && has(e.valueFrom) && has(e.valueFrom.secretKeyRef) && !has(e.valueFrom.configMapKeyRef) && !has(e.valueFrom.fieldRef) && !has(e.valueFrom.resourceFieldRef) && e.valueFrom.secretKeyRef.name == {json.dumps(i["existingSecret"])} && e.valueFrom.secretKeyRef.key == {json.dumps(i["secretKey"])} && (!has(e.valueFrom.secretKeyRef.optional) || !e.valueFrom.secretKeyRef.optional) : e.name in {json.dumps(values)} && has(e.value) && e.value == {json.dumps(values)}[e.name] && !has(e.valueFrom))', 'Identity, origin and secret wiring must exactly match the platform contract'),
        (f'(!has({container}.envFrom) || {container}.envFrom.size() == 0) && (!has({container}.command) || {container}.command.size() == 0) && (!has({container}.args) || {container}.args.size() == 0) && !has({container}.lifecycle)', 'No environment import, command override or lifecycle code is allowed'),
        (f'(!has({container}.volumeMounts) || {container}.volumeMounts.size() == 0) && (!has({container}.volumeDevices) || {container}.volumeDevices.size() == 0) && (!has({container}.workingDir) || {container}.workingDir == "")', 'No filesystem injection or working-directory override is allowed'),
        (f'(!has({p}.hostNetwork) || !{p}.hostNetwork) && (!has({p}.hostPID) || !{p}.hostPID) && (!has({p}.hostIPC) || !{p}.hostIPC) && (!has({p}.hostAliases) || {p}.hostAliases.size() == 0) && !has({p}.dnsConfig) && (!has({p}.dnsPolicy) || {p}.dnsPolicy == "ClusterFirst") && !has({p}.runtimeClassName)', 'Host access, custom DNS and runtime overrides are forbidden'),
        (f'has({p}.securityContext) && {p}.securityContext.runAsNonRoot == true && {p}.securityContext.runAsUser == 1000 && {p}.securityContext.runAsGroup == 1000 && {p}.securityContext.seccompProfile.type == "RuntimeDefault"', 'Pod must use the platform non-root seccomp profile'),
        (f'has({container}.securityContext) && {container}.securityContext.allowPrivilegeEscalation == false && {container}.securityContext.readOnlyRootFilesystem == true && (!has({container}.securityContext.privileged) || !{container}.securityContext.privileged) && {container}.securityContext.capabilities.drop == ["ALL"] && (!has({container}.securityContext.capabilities.add) || {container}.securityContext.capabilities.add.size() == 0) && (!has({container}.securityContext.runAsUser) || {container}.securityContext.runAsUser == 1000) && (!has({container}.securityContext.runAsGroup) || {container}.securityContext.runAsGroup == 1000) && (!has({container}.securityContext.runAsNonRoot) || {container}.securityContext.runAsNonRoot) && (!has({container}.securityContext.seccompProfile) || {container}.securityContext.seccompProfile.type == "RuntimeDefault")', 'Container must retain restricted security settings'),
        (f'has({container}.ports) && {container}.ports.size() == 1 && {container}.ports[0].name == "http" && {container}.ports[0].containerPort == 3000 && (!has({container}.ports[0].hostPort) || {container}.ports[0].hostPort == 0) && (!has({container}.ports[0].hostIP) || {container}.ports[0].hostIP == "")', 'Only the internal application port is allowed'),
    ]
    checks += [(f'(!has({p}.securityContext.sysctls) || {p}.securityContext.sysctls.size() == 0) && !has({p}.securityContext.seLinuxOptions) && !has({p}.securityContext.windowsOptions) && (!has({p}.securityContext.appArmorProfile) || {p}.securityContext.appArmorProfile.type == "RuntimeDefault") && (!has({container}.securityContext.procMount) || {container}.securityContext.procMount == "Default") && !has({container}.securityContext.seLinuxOptions) && !has({container}.securityContext.windowsOptions) && (!has({container}.securityContext.appArmorProfile) || {container}.securityContext.appArmorProfile.type == "RuntimeDefault")', 'Additional operating-system security overrides are forbidden'),
               (f'(!has({container}.stdin) || !{container}.stdin) && (!has({container}.stdinOnce) || !{container}.stdinOnce) && (!has({container}.tty) || !{container}.tty) && (!has({p}.shareProcessNamespace) || !{p}.shareProcessNamespace)', 'Interactive and shared process modes are forbidden')]
    for probe in ('livenessProbe', 'readinessProbe', 'startupProbe'):
        path = container + '.' + probe
        checks.append((f'!has({path}) || (has({path}.httpGet) && !has({path}.exec) && !has({path}.tcpSocket) && !has({path}.grpc) && {path}.httpGet.path == "/healthz" && {path}.httpGet.port == "http" && (!has({path}.httpGet.host) || {path}.httpGet.host == "") && (!has({path}.httpGet.httpHeaders) || {path}.httpGet.httpHeaders.size() == 0))', 'Health probes must not inject commands or alternate destinations'))
    return checks


def admission(c):
    result = []
    for name, group, version, resources, prefix in [
        ('portal-template-contract', 'apps', 'v1', ['deployments', 'replicasets'], 'object.spec.template.spec'),
        ('portal-pod-contract', '', 'v1', ['pods', 'pods/ephemeralcontainers'], 'object.spec')]:
        validations = workload_validations(c, prefix)
        if name == 'portal-template-contract':
            validations += [('request.kind.kind != "Deployment" || (object.metadata.name == "home-portal" && object.spec.replicas == 1 && object.spec.strategy.type == "Recreate")', 'Only the single platform-reviewed portal deployment is allowed')]
        result.extend([policy(name, [{'apiGroups': [group], 'apiVersions': [version], 'resources': resources, 'operations': ['CREATE', 'UPDATE']}], validations, c), binding(name)])
    principal = f'system:serviceaccount:{c["fleetAgentNamespace"]}:{c["deployerServiceAccount"]}'
    name = 'portal-deployer-surface'
    result.extend([policy(name, [{'apiGroups': ['*'], 'apiVersions': ['*'], 'resources': ['*', '*/*'], 'operations': ['CREATE', 'UPDATE', 'DELETE', 'CONNECT']}],
        [(f'request.namespace == {json.dumps(c["namespace"])} && (request.resource.group == "apps" && request.resource.resource == "deployments" && request.subResource == "" || request.resource.group == "" && request.resource.resource == "services" && request.subResource == "")', 'Tenant deployer may mutate only Deployment and Service resources')], c, 'request.userInfo.username == ' + json.dumps(principal)), binding(name)])
    name = 'portal-service-contract'
    result.extend([policy(name, [{'apiGroups': [''], 'apiVersions': ['v1'], 'resources': ['services'], 'operations': ['CREATE', 'UPDATE']}], [
        ('object.metadata.name == "home-portal" && object.spec.type == "ClusterIP" && (!has(object.spec.externalIPs) || object.spec.externalIPs.size() == 0) && !has(object.spec.externalName)', 'Only the internal portal ClusterIP Service is allowed'),
        ('object.spec.selector.size() == 1 && object.spec.selector["app.kubernetes.io/name"] == "perkforge-portal" && object.spec.ports.size() == 1 && object.spec.ports[0].port == 3000 && object.spec.ports[0].targetPort == "http"', 'Service must route only to the approved portal port')], c), binding(name)])
    return result


def resources(c):
    # Reuse reviewed platform-only RBAC/NetworkPolicy definitions, never tenant manifests.
    templates = TEMPLATES
    objects = []
    for filename in ('rbac.yaml', 'networkpolicy.yaml', 'fleet-resources.yaml'):
        objects.extend(yaml.safe_load_all((templates / filename).read_text()))
    objects.append({'apiVersion': 'fleet.cattle.io/v1alpha1', 'kind': 'GitRepo',
        'metadata': {'name': 'tenant-home-portal', 'namespace': 'fleet-home-portal',
                     'labels': {'platform.perkforge.io/tenant': 'home', 'platform.perkforge.io/application': 'portal'}},
        'spec': {'repo': TENANT_REPO, 'revision': c['tenantRevision'], 'paused': c['lifecycle']['state'] != 'active',
                 'targetNamespace': c['namespace'], 'serviceAccount': c['deployerServiceAccount'],
                 'keepResources': True, 'paths': ['bundles/portal'],
                 'targets': [{'name': 'local', 'clusterName': 'local'}]}})
    objects.append({'apiVersion': 'v1', 'kind': 'ConfigMap', 'metadata': {'name': 'portal-platform-values', 'namespace': c['namespace']}, 'immutable': True, 'data': {'values.yaml': yaml.safe_dump(helm_values(c), sort_keys=False)}})
    return objects + admission(c)


def outputs(c):
    validate(c)
    return {'resources.yaml': yaml.safe_dump_all(resources(c), sort_keys=False),
            'identity-plan.json': json.dumps(identity_plan(c), indent=2) + '\n',
            'helm-values.yaml': yaml.safe_dump(helm_values(c), sort_keys=False),
            'tenant-fleet-reference.yaml': yaml.safe_dump({'helm': {'valuesFrom': [{'configMapKeyRef': {'name': 'portal-platform-values', 'namespace': c['namespace'], 'key': 'values.yaml'}}]}}, sort_keys=False)}


def contract_for(catalog, tenant_id='home', application_id='portal'):
    import copy
    if (tenant_id, application_id) != ('home', 'portal'):
        raise ValueError('Only the Home portal application is supported')
    tenant = next((t for t in catalog['tenants'] if t['id'] == tenant_id), None)
    if tenant is None or application_id not in tenant.get('applications', {}):
        raise ValueError('Home portal application is absent from the catalog')
    if tenant['cluster'] != 'local':
        raise ValueError('Portal application currently supports Home on the local cluster only')
    if tenant.get('classification') != 'protected' or tenant['identity']['provider'] != 'keycloak':
        raise ValueError('Portal remains a protected Home Keycloak application')
    c = copy.deepcopy(tenant['applications'][application_id])
    if not isinstance(c,dict) or not isinstance(c.get('identity'),dict):
        raise ValueError('Application and identity must be mappings')
    if 'kubernetesVersion' in c or 'groups' in c.get('identity', {}):
        raise ValueError('Application must inherit cluster version and Home groups')
    c['kubernetesVersion'] = next(x['podSecurityVersion'] for x in catalog['clusters'] if x['name']==tenant['cluster']).removeprefix('v')
    c['identity']['groups'] = [tenant['identity']['groups'][r] for r in ('admins','developers','viewers')]
    validate(c)
    if c['lifecycle']['state'] == 'disabled' and any(e['namespace']==c['namespace'] for e in tenant['environments']):
        raise ValueError('Disabled means unprovisioned; an allocated portal namespace must remain paused or active')
    if c['lifecycle']['state'] != 'disabled' and not any(e['namespace']==c['namespace'] for e in tenant['environments']):
        raise ValueError('Provisioned portal requires an explicitly budgeted Home environment namespace')
    return c


def load_contract():
    from tenant_catalog import load_catalog
    return contract_for(load_catalog(ROOT/'local-lab/tenant-config/tenants.yaml'))


def validate_applications(catalog):
    for tenant in catalog['tenants']:
        apps=tenant.get('applications', {})
        if not isinstance(apps,dict) or (apps and (tenant['id']!='home' or set(apps)!={'portal'})):
            raise ValueError('Only applications.portal on existing Home is supported')
        if apps:
            contract_for(catalog)


def active_resources(catalog):
    validate_applications(catalog)
    home=next((t for t in catalog['tenants'] if t['id']=='home'), {})
    if not home.get('applications'):
        return []
    c=contract_for(catalog)
    if c['lifecycle']['state']=='disabled':
        return []
    # Base tenant foundation already owns default-deny for protected namespaces.
    result=[o for o in resources(c) if not (o["kind"]=="NetworkPolicy" and o["metadata"]["name"]=="default-deny")]
    for obj in result:
        obj['metadata'].setdefault('labels', {}).update({'platform.perkforge.io/tenant':'home', 'platform.perkforge.io/application':'portal', 'platform.perkforge.io/managed-by':'tenant-application'})
    return result
